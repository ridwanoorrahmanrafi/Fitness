/**
 * Retrieves the local & remote media paths and biometric tempo for any exercise.
 */
export function getExerciseMedia(exerciseId: string): ExerciseMediaItem {
  const item = EXERCISE_MEDIA_MAP[exerciseId];
  const localGif = `/exercises/${exerciseId}.gif`;
  const remoteFallback = item?.remoteFallbackGif ?? `${CDN_BASE}/pectorals/push-up.gif`;

  return {
    id: exerciseId,
    name: item?.name ?? exerciseId.replace(/_/g, " "),
    localGif,
    remoteFallbackGif: remoteFallback,
    muscleCategory: item?.muscleCategory ?? "general",
    primaryMuscleFocus: item?.primaryMuscleFocus ?? ["full body"],
    tempo: item?.tempo ?? { eccentric: 3, pause: 1, concentric: 1 },
    keyBreathingCue:
      item?.keyBreathingCue ??
      "Inhale on eccentric lowering (3 seconds) · Exhale forcefully on concentric drive",
  };
}
