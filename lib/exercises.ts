import type { Equipment, Exercise, Level, Muscle, Pattern, WarmupMove } from "./types";

type Opts = {
  timed?: boolean;
  perSide?: boolean;
  loaded?: boolean;
  /** true = jumping / ballistic, i.e. NOT low impact */
  impact?: boolean;
  easier?: string;
  harder?: string;
};

function ex(
  id: string,
  name: string,
  muscles: Muscle[],
  pattern: Pattern,
  requires: Equipment[],
  level: 1 | 2 | 3,
  cues: string,
  o: Opts = {},
): Exercise {
  return {
    id,
    name,
    muscles,
    pattern,
    requires,
    level,
    lowImpact: !o.impact,
    timed: o.timed,
    perSide: o.perSide,
    loaded: o.loaded,
    cues,
    easier: o.easier,
    harder: o.harder,
  };
}

